
#include "farmer.h"
#include "primitives.h"
#include <GL/freeglut.h>

void drawFarmer(float x, float y, float z,
                float scale, float hipAngle,
                float legAngle, float armAngle)
{
    glPushMatrix();

    glTranslatef(x, y, z);
    glScalef(scale, scale, scale);

    // ================= LOWER BODY =================
    glPushMatrix();
    glTranslatef(0.0f, 0.75f, 0.0f);
    glRotatef(legAngle, 1.0f, 0.0f, 0.0f);
    glTranslatef(0.0f, -0.75f, 0.0f);

    // Boots
    drawCube(-0.13, 0.10, 0.08, 0.25, 0.16, 0.35, 0.20, 0.10, 0.04);
    drawCube(0.13, 0.10, 0.08, 0.25, 0.16, 0.35, 0.20, 0.10, 0.04);

    // Boot soles
    drawCube(-0.13, 0.025, 0.10, 0.27, 0.035, 0.37, 0.08, 0.045, 0.02);
    drawCube(0.13, 0.025, 0.10, 0.27, 0.035, 0.37, 0.08, 0.045, 0.02);

    // Boot highlights
    drawCube(-0.13, 0.12, 0.258, 0.12, 0.025, 0.012, 0.35, 0.20, 0.08);
    drawCube(0.13, 0.12, 0.258, 0.12, 0.025, 0.012, 0.35, 0.20, 0.08);

    // Trousers
    drawCube(-0.13, 0.43, 0, 0.20, 0.55, 0.20, 0.12, 0.20, 0.55);
    drawCube(0.13, 0.43, 0, 0.20, 0.55, 0.20, 0.12, 0.20, 0.55);

    glPopMatrix();

    // ================= UPPER BODY =================
    glPushMatrix();

    glTranslatef(0.0f, 0.75f, 0.0f);
    glRotatef(hipAngle, 1.0f, 0.0f, 0.0f);
    glTranslatef(0.0f, -0.75f, 0.0f);

    // Shirt
    drawSphere(0, 1.17, 0, 0.34, 0.40, 0.22, 0.12, 0.42, 0.16);

    // Shirt collar
    drawSphereRot(-0.09, 1.48, 0.14, 0.09, 0.045, 0.025,
                  0, 0, -25, 0.08, 0.30, 0.12);
    drawSphereRot(0.09, 1.48, 0.14, 0.09, 0.045, 0.025,
                  0, 0, 25, 0.08, 0.30, 0.12);

    // Overalls
    drawCube(0, 0.98, 0.20, 0.38, 0.28, 0.04, 0.12, 0.20, 0.55);
    drawCube(-0.18, 1.35, 0.17, 0.07, 0.35, 0.04, 0.12, 0.20, 0.55);
    drawCube(0.18, 1.35, 0.17, 0.07, 0.35, 0.04, 0.12, 0.20, 0.55);

    drawSphere(-0.18, 1.38, 0.20, 0.035, 0.035, 0.02, 0.95, 0.72, 0.20);
    drawSphere(0.18, 1.38, 0.20, 0.035, 0.035, 0.02, 0.95, 0.72, 0.20);

    drawCube(0, 1.04, 0.228, 0.16, 0.12, 0.018, 0.08, 0.16, 0.43);
    drawSphere(0, 1.095, 0.25, 0.018, 0.018, 0.012, 0.95, 0.72, 0.20);

    drawCube(-0.13, 0.98, 0.225, 0.012, 0.20, 0.008, 0.35, 0.48, 0.75);
    drawCube(0.13, 0.98, 0.225, 0.012, 0.20, 0.008, 0.35, 0.48, 0.75);

    // ================= ANIMATED LEFT ARM =================
    glPushMatrix();
    glTranslatef(-0.38f, 1.30f, 0.0f);
    glRotatef(armAngle, 1.0f, 0.0f, 0.0f);
    glTranslatef(0.38f, -1.30f, 0.0f);

    drawSphereRot(-0.38, 1.30, 0, 0.14, 0.18, 0.14,
                  0, 0, 15, 0.12, 0.42, 0.16);
    drawSphere(-0.40, 1.02, 0, 0.105, 0.20, 0.105, 0.55, 0.32, 0.18);
    drawSphere(-0.40, 0.87, 0, 0.09, 0.11, 0.09, 0.55, 0.32, 0.18);

    glPopMatrix();

    // ================= ANIMATED RIGHT ARM =================
    glPushMatrix();
    glTranslatef(0.38f, 1.30f, 0.0f);
    glRotatef(armAngle, 1.0f, 0.0f, 0.0f);
    glTranslatef(-0.38f, -1.30f, 0.0f);

    drawSphereRot(0.38, 1.30, 0, 0.14, 0.18, 0.14,
                  0, 0, -15, 0.12, 0.42, 0.16);
    drawSphere(0.40, 1.02, 0, 0.105, 0.20, 0.105, 0.55, 0.32, 0.18);
    drawSphere(0.40, 0.87, 0, 0.09, 0.11, 0.09, 0.55, 0.32, 0.18);

    glPopMatrix();

    // Neck
    drawSphere(0, 1.53, 0, 0.12, 0.13, 0.12, 0.55, 0.32, 0.18);

    // Head
    drawSphere(0, 1.78, 0, 0.24, 0.27, 0.22, 0.55, 0.32, 0.18);

    // Ears
    drawSphere(-0.24, 1.78, 0, 0.06, 0.08, 0.06, 0.55, 0.32, 0.18);
    drawSphere(0.24, 1.78, 0, 0.06, 0.08, 0.06, 0.55, 0.32, 0.18);

    // Eyes
    drawSphere(-0.09, 1.83, 0.205, 0.05, 0.055, 0.025, 1, 1, 1);
    drawSphere(0.09, 1.83, 0.205, 0.05, 0.055, 0.025, 1, 1, 1);

    drawSphere(-0.09, 1.83, 0.229, 0.023, 0.030, 0.015, 0.02, 0.02, 0.02);
    drawSphere(0.09, 1.83, 0.229, 0.023, 0.030, 0.015, 0.02, 0.02, 0.02);

    drawSphere(-0.098, 1.845, 0.243, 0.008, 0.009, 0.005, 1, 1, 1);
    drawSphere(0.082, 1.845, 0.243, 0.008, 0.009, 0.005, 1, 1, 1);

    // Eyebrows
    drawSphereRot(-0.09, 1.91, 0.205, 0.055, 0.012, 0.012,
                  0, 0, -5, 0.12, 0.07, 0.03);
    drawSphereRot(0.09, 1.91, 0.205, 0.055, 0.012, 0.012,
                  0, 0, 5, 0.12, 0.07, 0.03);

    // Nose and cheeks
    drawSphere(0, 1.75, 0.22, 0.045, 0.04, 0.025, 0.40, 0.20, 0.12);
    drawSphere(-0.15, 1.74, 0.19, 0.035, 0.025, 0.015, 0.65, 0.36, 0.24);
    drawSphere(0.15, 1.74, 0.19, 0.035, 0.025, 0.015, 0.65, 0.36, 0.24);
    drawSphere(0, 1.675, 0.213, 0.055, 0.012, 0.008, 0.20, 0.06, 0.04);

    // Hair
    drawSphere(0, 1.98, 0, 0.23, 0.09, 0.21, 0.12, 0.07, 0.03);

    // Straw hat
    drawSphere(0, 2.02, 0, 0.36, 0.05, 0.30, 0.85, 0.65, 0.22);
    drawSphere(0, 2.10, 0, 0.21, 0.12, 0.20, 0.85, 0.65, 0.22);
    drawSphere(0, 2.075, 0, 0.215, 0.025, 0.205, 0.40, 0.22, 0.07);
    drawSphere(-0.12, 2.085, 0.17, 0.025, 0.025, 0.015, 0.25, 0.45, 0.12);

    glPopMatrix();
    glPopMatrix();
}
